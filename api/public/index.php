<?php

declare(strict_types=1);

use Laminas\HttpHandlerRunner\Emitter\SapiEmitter;
use League\Route\Router;
use League\Route\RouteGroup;
use League\Route\Strategy\JsonStrategy;
use Nyholm\Psr7\Factory\Psr17Factory;
use Nyholm\Psr7Server\ServerRequestCreator;
use Ww2\Account\AccountService;
use Ww2\Account\PlayerSession;
use Ww2\Account\PlayerStore;
use Ww2\Account\SignInAttempts;
use Ww2\Base\Alerts;
use Ww2\Base\BaseFounder;
use Ww2\Base\BaseOverview;
use Ww2\Base\BaseStore;
use Ww2\Base\Attacks;
use Ww2\Base\Battle;
use Ww2\Base\BattleStore;
use Ww2\Base\CampStore;
use Ww2\Base\CaptureCombats;
use Ww2\Base\Garrison;
use Ww2\Base\LifeEvents;
use Ww2\Base\EventLog;
use Ww2\Base\Gifts;
use Ww2\Base\Hangar;
use Ww2\Base\HangarStore;
use Ww2\Base\Headquarters;
use Ww2\Base\Holdings;
use Ww2\Base\PlayerActivity;
use Ww2\Base\Rebuilding;
use Ww2\Base\Mechanics;
use Ww2\Base\Roster;
use Ww2\Base\Stationings;
use Ww2\Base\SupplyIncome;
use Ww2\Base\StationingStore;
use Ww2\Base\Upgrades;
use Ww2\Base\Warehouse;
use Ww2\Base\Workshop;
use Ww2\Clock\GameClockStore;
use Ww2\Database\DatabaseSettings;
use Ww2\Database\Migrator;
use Ww2\Database\PdoDatabase;
use Ww2\Http\AccountController;
use Ww2\Http\BaseController;
use Ww2\Http\HealthController;
use Ww2\Http\MigrationMiddleware;
use Ww2\Http\SessionController;
use Ww2\Http\TerrainPatchController;
use Ww2\Mission\Dogfight\Dogfight;
use Ww2\Mission\FlightAlertStore;
use Ww2\Mission\MissionGenerator;
use Ww2\Mission\MissionResolver;
use Ww2\Mission\MissionStore;
use Ww2\Mission\WeatherForecast;
use Ww2\Http\TerrainController;
use Ww2\Http\WorldController;
use Ww2\Squadron\PilotGenerator;
use Ww2\Squadron\SquadronFounder;
use Ww2\Squadron\SquadronStore;
use Ww2\Terrain\TerrainGenerator;
use Ww2\Terrain\TilePatchGenerator;
use Ww2\World\AiCamps;
use Ww2\World\AiTurn;
use Ww2\World\Bases;
use Ww2\World\Instances;
use Ww2\World\SitePlaces;

require dirname(__DIR__) . '/vendor/autoload.php';

$database = new PdoDatabase(DatabaseSettings::fromEnvironmentFile(dirname(__DIR__, 2)));

$psr17Factory = new Psr17Factory();
$requestCreator = new ServerRequestCreator($psr17Factory, $psr17Factory, $psr17Factory, $psr17Factory);

$players = new PlayerStore($database);
$accounts = new AccountService($players, new SignInAttempts($database));
$session = new PlayerSession();
$squadrons = new SquadronStore($database);
$pilotGenerator = new PilotGenerator();
$squadronFounder = new SquadronFounder($squadrons, $pilotGenerator);
$baseStore = new BaseStore($database);
$clocks = new GameClockStore($database);
$baseFounder = new BaseFounder($baseStore);
$missions = new MissionStore($database);
$hangarStore = new HangarStore($database);
$events = new EventLog($database, $clocks);
$upgrades = new Upgrades($database, $baseStore, $squadronFounder);
$camps = new CampStore($database);
$activity = new PlayerActivity($database);
$stationingStore = new StationingStore($database);
$battleStore = new BattleStore($database, $stationingStore);
$aiCamps = new AiCamps($database);
$bases = new Bases($database, new Instances($database), $aiCamps, $squadronFounder, $baseFounder, $battleStore);
$battle = new Battle($database, $battleStore, $squadronFounder, $baseFounder, $bases);
$warehouse = new Warehouse($database, $baseStore, $upgrades, $camps);
$mechanics = new Mechanics($baseStore, $hangarStore, $squadrons);
$workshop = new Workshop($database, $baseStore, $clocks, $mechanics, $upgrades, $camps, $squadrons);
$alerts = new Alerts($database, $baseStore, $clocks, new FlightAlertStore($database), new Dogfight());
$hangar = new Hangar($database, $baseStore, $hangarStore, $missions, $squadrons, $clocks, $mechanics, $events, $camps);
$roster = new Roster($database, $baseStore, $missions, $squadrons, $clocks, $pilotGenerator, $stationingStore);
$garrison = new Garrison($squadrons, $stationingStore, $missions, $hangarStore);
$sitePlaces = SitePlaces::fromFile(dirname(__DIR__) . '/data/site-places.json');
$holdings = new Holdings($database, $bases, $baseFounder, $squadrons, $stationingStore, $clocks, $events, $garrison, $missions, $squadronFounder, new AiTurn($database, $bases, $aiCamps, $sitePlaces, $squadronFounder, $baseFounder, $battleStore));
$stationings = new Stationings($database, $baseStore, $baseFounder, $stationingStore, $squadrons, $missions, $hangarStore, $warehouse, $bases, $clocks, $events, $sitePlaces);
$missionGenerator = new MissionGenerator();
$attacks = new Attacks($bases, $camps, $garrison, $holdings, $activity, $stationings, $missionGenerator, $squadrons, $events, $clocks, $sitePlaces);
$resolver = new MissionResolver();
$headquarters = new Headquarters($database, $baseStore, $missions, $squadrons, $clocks, $hangarStore, $events, $battleStore, $missionGenerator, new WeatherForecast(), $resolver, $alerts, $stationingStore, $camps, $attacks, $bases, $garrison, new CaptureCombats($resolver));
$overview = new BaseOverview($baseStore, $warehouse, $workshop, $headquarters, $hangar, $roster, $upgrades, $battle, $squadrons, $events, $clocks, $bases, $stationings, $camps, $attacks, new SupplyIncome($database, $baseStore, $bases, $sitePlaces), $garrison, new LifeEvents($database, $events, $squadrons));
$gifts = new Gifts($database, $baseStore, $squadrons, $missions, $hangarStore, $bases, $events, $stationingStore, $clocks);
$baseController = new BaseController($overview, $warehouse, $workshop, $headquarters, $hangar, $roster, $upgrades, $battle, $alerts, $bases, $session, $gifts, $stationings, $holdings, $events, new Rebuilding($database, $baseStore, $camps), $activity);
$worldController = new WorldController($bases, $overview, $session, $holdings);

$router = new Router();
$router->setStrategy(new JsonStrategy($psr17Factory));
$router->get('/api/health', new HealthController($database));
$router->group('/api', function (RouteGroup $routes) use ($accounts, $players, $session, $baseController, $worldController): void {
    $routes->get('/terrain', new TerrainController(new TerrainGenerator()));
    $routes->get('/terrain/patch', new TerrainPatchController(new TilePatchGenerator()));
    $routes->post('/account', new AccountController($accounts, $session));
    $routes->get('/world/sites', [$worldController, 'sites']);
    $routes->get('/world/map', [$worldController, 'map']);
    $routes->post('/world/claim', [$worldController, 'claim']);
    $routes->get('/base', [$baseController, 'show']);
    $routes->get('/base/journal', [$baseController, 'journal']);
    $routes->post('/base/select', [$baseController, 'selectBase']);
    $routes->post('/base/gifts/pilot', [$baseController, 'givePilot']);
    $routes->post('/base/gifts/aircraft', [$baseController, 'giveAircraft']);
    $routes->post('/base/stationings/send', [$baseController, 'sendStationing']);
    $routes->post('/base/stationings/supply', [$baseController, 'sendSupply']);
    $routes->post('/base/stationings/recall', [$baseController, 'recallStationing']);
    $routes->post('/base/purchase', [$baseController, 'buy']);
    $routes->post('/base/production', [$baseController, 'produce']);
    $routes->post('/base/workshop/mechanics/recruit', [$baseController, 'recruitMechanic']);
    $routes->post('/base/hangar/rebuild', [$baseController, 'rebuildAircraft']);
    $routes->post('/base/missions/launch', [$baseController, 'launchMission']);
    $routes->post('/base/missions/attack', [$baseController, 'attackCamp']);
    $routes->post('/base/missions/return', [$baseController, 'receiveMission']);
    $routes->post('/base/alerts/start', [$baseController, 'startAlert']);
    $routes->post('/base/alerts/play', [$baseController, 'playAlert']);
    $routes->post('/base/alerts/finish', [$baseController, 'finishAlert']);
    $routes->post('/base/alerts/flak', [$baseController, 'finishFlak']);
    $routes->post('/base/hangar/inspect', [$baseController, 'inspectAircraft']);
    $routes->post('/base/hangar/repair', [$baseController, 'repairAircraft']);
    $routes->post('/base/pilots/rest', [$baseController, 'restPilot']);
    $routes->post('/base/pilots/recruit', [$baseController, 'recruitPilot']);
    $routes->post('/base/upgrades/buy', [$baseController, 'buyUpgrade']);
    $routes->post('/base/reset', [$baseController, 'resetBase']);
    $routes->post('/base/buildings/rebuild', [$baseController, 'rebuild']);
    $sessionController = new SessionController($accounts, $players, $session);
    $routes->get('/session', [$sessionController, 'show']);
    $routes->post('/session', [$sessionController, 'signIn']);
    $routes->delete('/session', [$sessionController, 'signOut']);
})->middleware(new MigrationMiddleware(new Migrator($database, dirname(__DIR__) . '/migrations')));

$response = $router->dispatch($requestCreator->fromGlobals());
(new SapiEmitter())->emit($response);
